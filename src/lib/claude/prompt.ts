import type { Asset, BrandKit } from '@/lib/spec/types';

function formatAssets(assets: Asset[]): string {
  if (assets.length === 0) return 'None - create a video using only skills/overlays';
  return assets
    .map((a) => {
      const dur = a.duration ? `${a.duration}s` : '';
      const dims = a.width && a.height ? `${a.width}x${a.height}` : '';
      return `- ${a.id}: ${a.type} "${a.filename}" ${dur} ${dims}`.trim();
    })
    .join('\n');
}

function formatBrandKit(brandKit?: BrandKit): string {
  if (!brandKit) return 'None - use defaults';
  const font = brandKit.primaryFont || 'Inter';
  const primary = brandKit.primaryColor || '#3b82f6';
  const secondary = brandKit.secondaryColor || '#8b5cf6';
  return `- Font: ${font}\n- Primary Color: ${primary}\n- Secondary Color: ${secondary}`;
}

export interface WebsiteContext {
  title: string;
  textContent: string;
  url: string;
}

export function buildWebsiteContext(ctx: WebsiteContext): string {
  return [
    'WEBSITE CONTEXT (scraped from provided URL):',
    `URL: ${ctx.url}`,
    `Site Title: ${ctx.title}`,
    '',
    'Key Content:',
    ctx.textContent.slice(0, 2000),
    '',
    'IMPORTANT INSTRUCTIONS FOR WEBSITE-BASED VIDEOS:',
    '1. Extract key messaging, taglines, and value propositions from the website content above',
    '2. Use TextReveal or KineticTypography to display main headlines (e.g., "FUEL YOUR BEST SELF")',
    '3. Use bullet points or sequential TextReveals for key features/benefits (e.g., "60+ SUPERFOODS", "DELICIOUS GUMMIES")',
    '4. Match the tone and brand personality evident in the website copy',
    '5. Use ImageSlideshow with scraped website images (check assets array for website-*.jpg or scraped images)',
    '6. Include the site title in IntroTitleCard',
    '7. Use website tagline or slogan in outro',
    '8. Keep text concise - extract only the most impactful phrases',
  ].join('\n');
}

